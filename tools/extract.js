#!/usr/bin/env node
// Converts the original 1983 source assets in digsrc_orig/ into js/assets.js.
//   node tools/extract.js
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'digsrc_orig');

function nums(s) {
  return s.split(',').map(t => t.trim()).filter(t => t.length).map(t => parseInt(t, 10));
}

// ---------- sprites (SPGEN.BAS output) ----------
const sprites = {};
const spriteDir = path.join(SRC, 'Sprites');
for (const file of fs.readdirSync(spriteDir).sort()) {
  if (!/\.SPR$/i.test(file)) continue;
  const text = fs.readFileSync(path.join(spriteDir, file), 'latin1');
  const img = /char\s+image_(\w+)\[\]\s*=\s*\{([^}]*)\}/.exec(text);
  const out = /char\s+outln_(\w+)\[\]\s*=\s*\{([^}]*)\}/.exec(text);
  const xw = /#define\s+X_WID_(\w+)\s+(\d+)/.exec(text);
  const yw = /#define\s+Y_WID_(\w+)\s+(\d+)/.exec(text);
  if (!img || !out || !xw || !yw) { console.warn('skipping', file); continue; }
  const name = img[1];
  const w = parseInt(xw[2], 10), h = parseInt(yw[2], 10);
  // every array is terminated by an extra 0 which is not part of the image
  const image = nums(img[2]).slice(0, w * h);
  const outline = nums(out[2]).slice(0, w * h);
  if (image.length !== w * h || outline.length !== w * h) throw new Error('bad size in ' + file);
  sprites[name] = { w, h, image, outline, file };
}

// ---------- font (CLib/CHAR__*.CHR) ----------
const font = {};
const fontNames = { PE: '.', UL: '_', SP: ' ' };
const fontDir = path.join(SRC, 'CLib');
for (const file of fs.readdirSync(fontDir).sort()) {
  const m = /^CHAR__(\w+)\.CHR$/i.exec(file);
  if (!m) continue;
  const text = fs.readFileSync(path.join(fontDir, file), 'latin1');
  const arr = /char\s+char_\w+\[\]\s*=\s*\{([^}]*)\}/.exec(text);
  const data = nums(arr[1]);
  const w = data[0], h = data[1];
  const ch = fontNames[m[1].toUpperCase()] || m[1].toUpperCase();
  font[ch] = { w, h, data: data.slice(2, 2 + w * h) };
}

// ---------- run length encoded title screen (TITLE.ASM) ----------
const titleText = fs.readFileSync(path.join(SRC, 'Source', 'TITLE.ASM'), 'latin1');
const rlesize = parseInt(/rlesize\s+dw\s+(\d+)/.exec(titleText)[1], 10);
const title = [];
const dbRe = /db\s+([0-9,\s]+)/g;
let m;
while ((m = dbRe.exec(titleText))) title.push(...nums(m[1]));
if (title.length < rlesize) throw new Error('title data short');
title.length = rlesize;

// ---------- level maps (Work/TX.C) ----------
const txText = fs.readFileSync(path.join(SRC, 'Work', 'TX.C'), 'latin1');
const levels = [];
const matRe = /char\s+mat_(\d)\[H_MAX\]\[W_MAX\]\s*=\s*\{([\s\S]*?)\};/g;
while ((m = matRe.exec(txText))) {
  const rows = [];
  const rowRe = /\{([^}]*)\}/g;
  let r;
  while ((r = rowRe.exec(m[2]))) {
    rows.push(r[1].split(',').map(c => c.trim().replace(/'/g, '')).map(c => c === '' ? ' ' : c).join(''));
  }
  levels[parseInt(m[1], 10) - 1] = rows;
}

// ---------- note tables (Work/NOTES.H + Work/TH.C) ----------
const notes = {};
const notesText = fs.readFileSync(path.join(SRC, 'Work', 'NOTES.H'), 'latin1');
const defRe = /#define\s+(\w+)\s+(\d+)/g;
while ((m = defRe.exec(notesText))) notes[m[1]] = parseInt(m[2], 10);
Object.assign(notes, { NS: 1, NE: 2, NQ: 4, NH: 8, NW: 16 });

const thText = fs.readFileSync(path.join(SRC, 'Work', 'TH.C'), 'latin1')
  .replace(/\/\*[\s\S]*?\*\//g, '');
const music = {};
const musRe = /int\s+(music\d)\[\]\s*=\s*\{([\s\S]*?)\};/g;
while ((m = musRe.exec(thText))) {
  music[m[1]] = m[2].split(',').map(t => t.trim()).filter(t => t.length).map(t => {
    if (/^\d+$/.test(t)) return parseInt(t, 10);
    if (!(t in notes)) throw new Error('unknown note ' + t);
    return notes[t];
  });
}

// ---------- random number table (Source/CLIB.C) ----------
const clibText = fs.readFileSync(path.join(SRC, 'Source', 'CLIB.C'), 'latin1');
const rndTable = nums(/char\s+rnd_table\[\]\s*=\s*\{([^}]*)\}/.exec(clibText)[1]);
if (rndTable.length !== 256) throw new Error('rnd table size ' + rndTable.length);

const out = '// Generated by tools/extract.js from the original source in digsrc_orig/. Do not edit.\n' +
  'const ASSETS = ' + JSON.stringify({ sprites, font, title, levels, music, notes, rndTable }) + ';\n';
fs.mkdirSync(path.join(ROOT, 'js'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'js', 'assets.js'), out);
console.log('sprites', Object.keys(sprites).length, 'font', Object.keys(font).length,
  'title bytes', title.length, 'levels', levels.length, 'music', Object.keys(music).map(k => k + ':' + music[k].length).join(' '));
